#!/usr/bin/env python3
# -*- coding: utf-8 -*-
r"""Filter existing FES2022b M2 QGIS screening grid conservatively.

Run from your project root on Windows:
    .\.venv-api\Scripts\python.exe .\scripts\17_filter_fes_native_candidates.py

Input (generated by 16_screen_fes2022b_qgis.py):
    data/processed/tide/fes2022b_m2_mask_grid.geojson

Outputs:
    data/processed/tide/fes2022b_m2_native_only_review.geojson
    data/processed/tide/fes2022b_m2_native_interior_review.geojson
    data/processed/tide/fes2022b_m2_native_only_review.csv

This is a MODEL MASK FILTER, NOT a shoreline/coastline validation. Points
should be visually checked against real coastline/bathymetry in QGIS.
Do NOT promote outputs directly to verified tide points.
"""

from __future__ import annotations

import csv
import json
import math
from pathlib import Path

ROOT = Path.cwd()
DIRECTORY = ROOT / "data" / "processed" / "tide"
INPUT = DIRECTORY / "fes2022b_m2_mask_grid.geojson"
ALL_OUT = DIRECTORY / "fes2022b_m2_native_only_review.geojson"
INTERIOR_OUT = DIRECTORY / "fes2022b_m2_native_interior_review.geojson"
CSV_OUT = DIRECTORY / "fes2022b_m2_native_only_review.csv"


def safe_round(value: object) -> float:
    return round(float(value), 6)


def geojson(features: list[dict]) -> dict:
    return {
        "type": "FeatureCollection",
        "name": "FES2022b M2 native model ocean grid (NOT shoreline-verified)",
        "features": features,
    }


def main() -> None:
    if not INPUT.exists():
        raise SystemExit(f"Missing input file: {INPUT}")

    data = json.loads(INPUT.read_text(encoding="utf-8-sig"))
    features = data.get("features")
    if not isinstance(features, list) or not features:
        raise SystemExit("Input must contain a nonempty GeoJSON FeatureCollection")

    props = [x.get("properties") or {} for x in features]
    lats = sorted({safe_round(p["lat"]) for p in props})
    lons = sorted({safe_round(p["lon"]) for p in props})
    lat_index = {lat: i for i, lat in enumerate(lats)}
    lon_index = {lon: i for i, lon in enumerate(lons)}

    grid = {}
    for p in props:
        grid[(lat_index[safe_round(p["lat"])], lon_index[safe_round(p["lon"])] )] = p
    if len(grid) != len(features):
        raise SystemExit("Duplicate grid coordinates in source GeoJSON")

    all_native = []
    native_interior = []
    csv_rows = []
    for (i, j), p in grid.items():
        if int(p.get("mask_code", -1)) != 0 or p.get("valid_m2") is not True:
            continue

        is_native_3x3 = all(
            grid.get((i + di, j + dj), {}).get("mask_code") == 0 and
            grid.get((i + di, j + dj), {}).get("valid_m2") is True
            for di in (-1, 0, 1) for dj in (-1, 0, 1)
        )

        new_properties = {
            "grid_lat": float(p["lat"]),
            "grid_lon": float(p["lon"]),
            "mask_code": 0,
            "mask_class": "OCEAN_NATIVE",
            "amplitude_cm": p.get("amplitude_cm"),
            "phase_deg": p.get("phase_deg"),
            "native_3x3": is_native_3x3,
            "priority": "NATIVE_INTERIOR_REVIEW" if is_native_3x3 else "NATIVE_EDGE_REVIEW",
            "coastline_check": "NOT_CHECKED",
            "validation_status": "REVIEW_ONLY",
            "note": "Model-native grid; verify offshore location independently",
        }
        feat = {
            "type": "Feature",
            "geometry": {
                "type": "Point",
                "coordinates": [float(p["lon"]), float(p["lat"])],
            },
            "properties": new_properties,
        }
        all_native.append(feat)
        csv_rows.append(new_properties)
        if is_native_3x3:
            native_interior.append(feat)

    ALL_OUT.write_text(json.dumps(geojson(all_native), ensure_ascii=False), encoding="utf-8")
    INTERIOR_OUT.write_text(json.dumps(geojson(native_interior), ensure_ascii=False), encoding="utf-8")
    with CSV_OUT.open("w", encoding="utf-8-sig", newline="") as f:
        if csv_rows:
            writer = csv.DictWriter(f, fieldnames=list(csv_rows[0].keys()))
            writer.writeheader()
            writer.writerows(csv_rows)

    n0 = sum(int(p.get("mask_code", -1)) == 0 for p in props)
    n1 = sum(int(p.get("mask_code", -1)) == 1 for p in props)
    print("FES2022b native M2 filter")
    print(f"Input grid: {len(features)} cells")
    print(f"Mask 0 native: {n0} cells (valid M2 candidates exported: {len(all_native)})")
    print(f"Mask 1 extrapolated: {n1} cells (not exported as offshore)")
    print(f"Native interior 3x3: {len(native_interior)} cells (still NOT shoreline-verified)")
    print(f"Wrote: {ALL_OUT}")
    print(f"Wrote: {INTERIOR_OUT}")
    print(f"Wrote: {CSV_OUT}")
    print("WARNING: Do not mark any of these as VERIFIED until checked against real coastline and model samples.")


if __name__ == "__main__":
    main()
